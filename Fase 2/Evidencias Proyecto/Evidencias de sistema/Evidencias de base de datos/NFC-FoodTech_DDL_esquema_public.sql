CREATE OR REPLACE FUNCTION public.cambiar_rol_hogar(p_hogar_id uuid, p_perfil_id uuid, p_rol text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_rol text := upper(trim(p_rol));
  v_actual text;
  v_admins integer;
begin
  if not public.es_admin_hogar(p_hogar_id) then
    raise exception 'Solo el administrador puede cambiar roles.';
  end if;

  if v_rol not in ('ADMIN', 'MIEMBRO') then
    raise exception 'Rol no válido.';
  end if;

  select rol into v_actual
    from public.hogar_miembro
   where hogar_id = p_hogar_id
     and perfil_id = p_perfil_id
     and estado = 'ACTIVO';

  if not found then
    raise exception 'El usuario no es miembro de este hogar.';
  end if;

  if v_actual = v_rol then
    return;
  end if;

  if v_actual = 'ADMIN' and v_rol = 'MIEMBRO' then
    select count(*) into v_admins
      from public.hogar_miembro
     where hogar_id = p_hogar_id
       and estado = 'ACTIVO'
       and rol = 'ADMIN';

    if v_admins <= 1 then
      raise exception 'El hogar debe tener al menos un administrador. Transfiere la administración a otro miembro primero.';
    end if;
  end if;

  update public.hogar_miembro
     set rol = v_rol
   where hogar_id = p_hogar_id
     and perfil_id = p_perfil_id;
end;
$function$;

