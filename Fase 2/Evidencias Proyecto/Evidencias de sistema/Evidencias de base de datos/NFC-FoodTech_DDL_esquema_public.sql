CREATE OR REPLACE FUNCTION public.dv_rut(cuerpo bigint)
 RETURNS character
 LANGUAGE plpgsql
 IMMUTABLE STRICT
 SET search_path TO ''
AS $function$
declare
  n bigint := cuerpo;
  suma integer := 0;
  mult integer := 2;
  resto integer;
begin
  if n <= 0 then
    return null;
  end if;
  while n > 0 loop
    suma := suma + (n % 10) * mult;
    n := n / 10;
    mult := case when mult = 7 then 2 else mult + 1 end;
  end loop;
  resto := 11 - (suma % 11);
  return case resto
           when 11 then '0'
           when 10 then 'K'
           else resto::text
         end;
end;
$function$;

CREATE OR REPLACE FUNCTION public.editar_item_inventario(p_item_id uuid, p_nueva_cantidad numeric DEFAULT NULL::numeric, p_nueva_ubicacion text DEFAULT NULL::text, p_cambiar_fecha boolean DEFAULT false, p_nueva_fecha date DEFAULT NULL::date, p_cambiar_precio boolean DEFAULT false, p_nuevo_precio integer DEFAULT NULL::integer, p_cambiar_observaciones boolean DEFAULT false, p_nuevas_observaciones text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_usuario uuid := auth.uid();
    v_item public.despensa_item%ROWTYPE;

    v_hoy date := (now() AT TIME ZONE 'America/Santiago')::date;

    v_cantidad numeric;
    v_inicial numeric;
    v_delta numeric;

    v_ubicacion text;
    v_cambio_ubicacion boolean;

    v_fecha date;
    v_estimada boolean;
    v_inicio_congelacion date;
    v_fecha_previa date;

    v_dias_congelado integer;
    v_aviso text;
BEGIN
    -- 1. AUTENTICACIÓN Y CUENTA ACTIVA
    IF v_usuario IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión.';
    END IF;

    IF NOT COALESCE(nfc_seguridad.cuenta_activa(), false) THEN
        RAISE EXCEPTION 'La cuenta no está activa.';
    END IF;

    -- 2. OBTENER Y BLOQUEAR EL ÍTEM
    SELECT *
    INTO v_item
    FROM public.despensa_item
    WHERE id = p_item_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'El alimento no existe.';
    END IF;

    IF NOT public.es_miembro_hogar(v_item.hogar_id) THEN
        RAISE EXCEPTION 'No tienes acceso a este alimento.';
    END IF;

    IF v_item.estado <> 'DISPONIBLE'
       OR v_item.cantidad_restante <= 0 THEN
        RAISE EXCEPTION
            'Solo puedes editar alimentos disponibles.';
    END IF;

    -- 3. AJUSTAR CANTIDAD SIN ALTERAR CONSUMOS
    v_cantidad := COALESCE(
        p_nueva_cantidad,
        v_item.cantidad_restante
    );

    IF v_cantidad <= 0
       OR v_cantidad > 9999999.999
       OR v_cantidad <> round(v_cantidad, 3) THEN
        RAISE EXCEPTION
            'La cantidad debe ser positiva y tener máximo 3 decimales.';
    END IF;

    v_delta := v_cantidad - v_item.cantidad_restante;

    v_inicial := v_item.cantidad_inicial + v_delta;

    IF v_inicial <= 0
       OR v_inicial > 9999999.999 THEN
        RAISE EXCEPTION 'Cantidad inicial corregida no válida.';
    END IF;

    -- 4. DETECTAR CAMBIO DE UBICACIÓN
    v_ubicacion := COALESCE(
        p_nueva_ubicacion,
        v_item.ubicacion
    );

    IF v_ubicacion NOT IN (
        'DESPENSA',
        'REFRIGERADOR',
        'CONGELADOR'
    ) THEN
        RAISE EXCEPTION 'Ubicación no válida.';
    END IF;

    v_cambio_ubicacion :=
        v_ubicacion <> v_item.ubicacion;

    -- 5. CONSERVAR DATOS DE FECHA
    v_fecha := v_item.fecha_vencimiento;
    v_estimada := v_item.vencimiento_estimado;
    v_inicio_congelacion := v_item.fecha_inicio_congelacion;
    v_fecha_previa := v_item.fecha_previa_congelacion;

    -- 6. VALIDAR PRECIO Y OBSERVACIONES
    IF COALESCE(p_cambiar_precio, false)
       AND p_nuevo_precio IS NOT NULL
       AND p_nuevo_precio < 0 THEN
        RAISE EXCEPTION 'El precio no puede ser negativo.';
    END IF;

    IF COALESCE(p_cambiar_observaciones, false)
       AND length(COALESCE(p_nuevas_observaciones, '')) > 500 THEN
        RAISE EXCEPTION
            'Las observaciones admiten máximo 500 caracteres.';
    END IF;

    -- 7. TRASLADO DE UBICACIÓN
    IF v_cambio_ubicacion THEN

        -- DESCONGELACIÓN
        IF v_item.ubicacion = 'CONGELADOR'
           AND v_ubicacion <> 'CONGELADOR' THEN

            -- Nunca conservar una fecha de meses de
            -- congelación como fecha de refrigeración.
            IF NOT COALESCE(p_cambiar_fecha, false)
               OR p_nueva_fecha IS NULL THEN
                RAISE EXCEPTION
                    'Al retirar un alimento del congelador debes indicar una nueva fecha de revisión.';
            END IF;

            v_inicio_congelacion := NULL;

            v_aviso :=
                'Se registró la salida del congelador. Revisa que la fecha indicada sea adecuada al alimento.';

        -- ENTRADA AL CONGELADOR
        ELSIF v_ubicacion = 'CONGELADOR'
              AND v_item.ubicacion <> 'CONGELADOR' THEN

            v_inicio_congelacion := v_hoy;
            v_fecha_previa := v_item.fecha_vencimiento;

            -- Prioridad: alimento específico.
            -- Respaldo: duración congelada de categoría.
            SELECT COALESCE(
                NULLIF(a.vida_util_congelado_dias, 0),
                NULLIF(c.vida_util_congelado_dias, 0)
            )
            INTO v_dias_congelado
            FROM public.alimento a
            LEFT JOIN public.categoria c
                ON c.id = a.categoria_id
            WHERE a.id = v_item.alimento_id;

            IF COALESCE(p_cambiar_fecha, false) THEN
                -- La fecha manual se procesa más abajo.
                NULL;

            ELSIF v_item.vencimiento_estimado = false THEN
                v_aviso :=
                    'Traslado registrado. Se conservó la fecha manual original.';

            ELSIF v_item.fecha_vencimiento IS NULL
               OR v_item.fecha_vencimiento < v_hoy THEN
                v_aviso :=
                    'Traslado registrado, pero no se extendió una fecha estimada ya superada o desconocida.';

            ELSIF v_dias_congelado IS NULL
               OR v_dias_congelado <= 0 THEN
                v_aviso :=
                    'Traslado registrado. Este alimento no tiene duración congelada configurada; revisa su fecha.';

            ELSE
                v_fecha := v_hoy + v_dias_congelado;
                v_estimada := true;

                v_aviso :=
                    'Traslado registrado. Se calculó una referencia de calidad congelada de '
                    || v_dias_congelado || ' días.';
            END IF;

        -- OTROS TRASLADOS
        ELSE
            v_aviso :=
                'Ubicación actualizada. La fecha no se recalculó automáticamente.';
        END IF;
    END IF;

    -- 8. CAMBIO MANUAL DE FECHA: TIENE PRIORIDAD
    IF COALESCE(p_cambiar_fecha, false) THEN
        v_fecha := p_nueva_fecha;
        v_estimada := false;
    END IF;

    -- 9. GUARDAR CAMBIOS
    UPDATE public.despensa_item
    SET
        cantidad_restante = v_cantidad,
        cantidad_inicial = v_inicial,

        ubicacion = v_ubicacion,

        fecha_vencimiento = v_fecha,
        vencimiento_estimado = v_estimada,

        fecha_inicio_congelacion = v_inicio_congelacion,
        fecha_previa_congelacion = v_fecha_previa,

        precio_clp = CASE
            WHEN COALESCE(p_cambiar_precio, false)
                THEN p_nuevo_precio
            ELSE precio_clp
        END,

        observaciones = CASE
            WHEN COALESCE(p_cambiar_observaciones, false)
                THEN NULLIF(trim(p_nuevas_observaciones), '')
            ELSE observaciones
        END

    WHERE id = p_item_id;

    -- 10. REGISTRAR AJUSTE DE CANTIDAD
    IF v_delta <> 0 THEN
        INSERT INTO public.movimiento (
            despensa_item_id,
            tipo,
            cantidad,
            ajuste_delta,
            registrado_por,
            fecha
        )
        VALUES (
            p_item_id,
            'AJUSTE',
            abs(v_delta),
            v_delta,
            v_usuario,
            now()
        );
    END IF;

    -- 11. REGISTRAR TRASLADO EN AUDITORÍA
    IF v_cambio_ubicacion THEN
        INSERT INTO public.auditoria (
            id,
            entidad,
            entidad_id,
            accion,
            perfil_id,
            antes,
            despues,
            fecha,
            motivo
        )
        VALUES (
            gen_random_uuid(),
            'despensa_item',
            p_item_id::text,
            'UPDATE',
            v_usuario,

            jsonb_build_object(
                'ubicacion', v_item.ubicacion,
                'fecha_vencimiento', v_item.fecha_vencimiento,
                'vencimiento_estimado', v_item.vencimiento_estimado
            ),

            jsonb_build_object(
                'ubicacion', v_ubicacion,
                'fecha_vencimiento', v_fecha,
                'vencimiento_estimado', v_estimada,
                'fecha_inicio_congelacion', v_inicio_congelacion,
                'fecha_previa_congelacion', v_fecha_previa
            ),

            now(),
            'TRASLADO_UBICACION'
        );
    END IF;

    -- 12. DEVOLVER RESULTADO A FLUTTER
    RETURN jsonb_build_object(
        'id', p_item_id,
        'cantidad_inicial', v_inicial,
        'cantidad_restante', v_cantidad,
        'ajuste_delta', v_delta,
        'ubicacion_anterior', v_item.ubicacion,
        'ubicacion', v_ubicacion,
        'traslado_registrado', v_cambio_ubicacion,
        'fecha_vencimiento', v_fecha,
        'vencimiento_estimado', v_estimada,
        'fecha_inicio_congelacion', v_inicio_congelacion,
        'fecha_previa_congelacion', v_fecha_previa,
        'aviso', v_aviso
    );
END;
$function$;

CREATE OR REPLACE FUNCTION public.es_admin(p_permiso text DEFAULT NULL::text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  select coalesce(auth.jwt() ->> 'aal', '') = 'aal2'
    and exists (
      select 1
      from public.perfil as p
      join public.perfil_rol as pr on pr.perfil_id = p.id
      join public.rol as r on r.id = pr.rol_id
      where p.id = auth.uid()
        and p.estado_cuenta = 'ACTIVA'
        and (p_permiso is null or exists (
          select 1
          from public.rol_permiso as rp
          join public.permiso as pe on pe.id = rp.permiso_id
          where rp.rol_id = r.id and pe.codigo = p_permiso
