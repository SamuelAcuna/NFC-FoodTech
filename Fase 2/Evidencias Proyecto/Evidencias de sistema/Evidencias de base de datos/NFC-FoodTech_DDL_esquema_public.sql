CREATE OR REPLACE FUNCTION nfc_m28_privado.cancelar_alertas_pendientes(p_perfil_id uuid DEFAULT NULL::uuid)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_canceladas integer := 0;
BEGIN

    UPDATE public.notificacion n
    SET estado = 'CANCELADA'

    WHERE
        -- Exclusivamente notificaciones del módulo M28.
        n.clave_dedup LIKE 'm28:%'

        -- No modificar notificaciones leídas,
        -- enviadas o canceladas anteriormente.
        AND n.estado = 'PENDIENTE'
        AND n.leida_en IS NULL

        -- NULL permite la revisión global desde Cron.
        AND (
            p_perfil_id IS NULL
            OR n.perfil_id = p_perfil_id
        )

        AND EXISTS (
            SELECT 1
            FROM public.plantilla_notificacion pm
            WHERE pm.id = n.plantilla_id
              AND pm.codigo IN (
                  'VENCIMIENTO_PROXIMO',
                  'PRODUCTO_VENCIDO',
                  'FECHA_INDICADA_PROXIMA',
                  'FECHA_INDICADA_SUPERADA'
              )
        )

        -- Si ya NO existe una condición válida
        -- que justifique el aviso, cancelarlo.
        AND NOT EXISTS (

            SELECT 1
            FROM public.despensa_item d

            JOIN public.hogar_miembro hm
                ON hm.hogar_id = d.hogar_id
               AND hm.perfil_id = n.perfil_id
               AND hm.estado = 'ACTIVO'

            JOIN public.perfil per
                ON per.id = n.perfil_id
               AND per.estado_cuenta = 'ACTIVA'

            JOIN public.preferencia_notificacion pref
                ON pref.perfil_id = n.perfil_id
               AND pref.habilitada = true

            JOIN public.plantilla_notificacion tp
                ON tp.id = pref.plantilla_id
               AND tp.codigo IN (
                   'VENCIMIENTO_PROXIMO',
                   'PRODUCTO_VENCIDO'
               )

            JOIN public.plantilla_notificacion tm
                ON tm.id = n.plantilla_id

            CROSS JOIN LATERAL (
                SELECT (
                    now() AT TIME ZONE per.zona_horaria
                )::date AS hoy
            ) fechas

            WHERE d.id = n.despensa_item_id

              -- El alimento todavía debe existir
              -- en el inventario disponible.
              AND d.estado = 'DISPONIBLE'
              AND d.cantidad_restante > 0
              AND d.fecha_vencimiento IS NOT NULL

              -- Si cambió la fecha, el aviso anterior
              -- ya no representa el registro actual.
              AND n.datos ->> 'fecha' =
                  d.fecha_vencimiento::text

              -- Si cambió el origen de la fecha,
              -- tampoco debe conservarse el aviso.
              AND n.datos ->> 'origen_fecha' =
                  CASE
                      WHEN d.vencimiento_estimado
                          THEN 'ESTIMADA'
                      ELSE 'MANUAL'
                  END

              -- El tipo de mensaje debe corresponder
              -- con el origen actual de la fecha.
              AND tm.codigo =
                  CASE
                      WHEN tp.codigo =
                          'VENCIMIENTO_PROXIMO'
                          AND d.vencimiento_estimado
                          THEN 'VENCIMIENTO_PROXIMO'

                      WHEN tp.codigo =
                          'VENCIMIENTO_PROXIMO'
                          AND NOT d.vencimiento_estimado
                          THEN 'FECHA_INDICADA_PROXIMA'

                      WHEN tp.codigo =
                          'PRODUCTO_VENCIDO'
                          AND d.vencimiento_estimado
                          THEN 'PRODUCTO_VENCIDO'

                      ELSE 'FECHA_INDICADA_SUPERADA'
                  END

              -- La notificación aún debe corresponder
              -- al período configurado por el usuario.
              AND (
                  (
                      tp.codigo = 'VENCIMIENTO_PROXIMO'

                      AND d.fecha_vencimiento >=
                          fechas.hoy

                      AND d.fecha_vencimiento <=
                          fechas.hoy + LEAST(
                              COALESCE(
                                  pref.dias_anticipacion,
                                  3
                              ),
                              14
                          )
                  )

                  OR

                  (
                      tp.codigo = 'PRODUCTO_VENCIDO'

                      AND d.fecha_vencimiento <
                          fechas.hoy
                  )
              )
        );

    GET DIAGNOSTICS v_canceladas = ROW_COUNT;

    RETURN v_canceladas;

END;
$function$;

CREATE OR REPLACE FUNCTION nfc_m28_privado.generar_alertas_programadas(p_perfil_id uuid DEFAULT NULL::uuid)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_generadas integer := 0;
BEGIN

    INSERT INTO public.notificacion (
        perfil_id,
        plantilla_id,
        despensa_item_id,
        datos,
        estado,
        programada_para,
        clave_dedup
    )

    SELECT
        per.id,
        plantilla_mensaje.id,
        d.id,

        jsonb_build_object(
            'alimento', a.nombre,
            'dias', GREATEST(
                d.fecha_vencimiento - fechas.hoy,
                0
            ),
            'fecha', d.fecha_vencimiento,
            'hogar', h.nombre,
            'cantidad', d.cantidad_restante,
            'unidad', a.unidad_base,
            'vencimiento_estimado',
                d.vencimiento_estimado,
            'origen_fecha',
                CASE
                    WHEN d.vencimiento_estimado
                        THEN 'ESTIMADA'
                    ELSE 'MANUAL'
                END
        ),

        'PENDIENTE',

        now(),

        -- MISMA clave que utiliza la función de Flutter.
        -- Evita avisos duplicados entre ambos procesos.
        concat(
            'm28:',
            per.id::text, ':',
            plantilla_mensaje.id::text, ':',
            d.id::text, ':',
            d.fecha_vencimiento::text
        )

    FROM public.perfil per

    JOIN public.hogar_miembro hm
        ON hm.perfil_id = per.id
       AND hm.estado = 'ACTIVO'

    JOIN public.hogar h
        ON h.id = hm.hogar_id

    JOIN public.despensa_item d
        ON d.hogar_id = hm.hogar_id
       AND d.estado = 'DISPONIBLE'
       AND d.cantidad_restante > 0
       AND d.fecha_vencimiento IS NOT NULL

    JOIN public.alimento a
        ON a.id = d.alimento_id

    -- Solo preferencias expresamente guardadas
    -- y habilitadas por el usuario.
    JOIN public.preferencia_notificacion pref
        ON pref.perfil_id = per.id
       AND pref.habilitada = true

    JOIN public.plantilla_notificacion
        AS plantilla_preferencia
        ON plantilla_preferencia.id = pref.plantilla_id
       AND plantilla_preferencia.codigo IN (
           'VENCIMIENTO_PROXIMO',
           'PRODUCTO_VENCIDO'
       )

    -- Diferenciar fecha estimada de fecha manual.
    JOIN public.plantilla_notificacion
        AS plantilla_mensaje
        ON plantilla_mensaje.codigo =
            CASE
                WHEN
                    plantilla_preferencia.codigo =
                        'VENCIMIENTO_PROXIMO'
                    AND d.vencimiento_estimado = true
                    THEN 'VENCIMIENTO_PROXIMO'

                WHEN
                    plantilla_preferencia.codigo =
                        'VENCIMIENTO_PROXIMO'
                    AND d.vencimiento_estimado = false
                    THEN 'FECHA_INDICADA_PROXIMA'

                WHEN
                    plantilla_preferencia.codigo =
                        'PRODUCTO_VENCIDO'
                    AND d.vencimiento_estimado = true
                    THEN 'PRODUCTO_VENCIDO'

                ELSE 'FECHA_INDICADA_SUPERADA'
            END

    CROSS JOIN LATERAL (
        SELECT
            (
                now() AT TIME ZONE per.zona_horaria
            )::date AS hoy,

            (
                now() AT TIME ZONE per.zona_horaria
            )::time AS hora_local
    ) AS fechas

    WHERE
        -- Solo cuentas activas.
        per.estado_cuenta = 'ACTIVA'

        -- Permite probar con un único usuario.
        AND (
            p_perfil_id IS NULL
            OR per.id = p_perfil_id
        )

        -- No generar antes de la hora configurada.
        -- Si no tiene hora, usar 09:00.
        AND fechas.hora_local >= COALESCE(
            pref.hora_envio,
            TIME '09:00'
        )

        AND (
            (
                plantilla_preferencia.codigo =
                    'VENCIMIENTO_PROXIMO'

                AND d.fecha_vencimiento >= fechas.hoy

                AND d.fecha_vencimiento <=
                    fechas.hoy + LEAST(
                        COALESCE(
                            pref.dias_anticipacion,
                            3
                        ),
                        14
                    )
            )

            OR

            (
                plantilla_preferencia.codigo =
                    'PRODUCTO_VENCIDO'

                AND d.fecha_vencimiento < fechas.hoy
            )
        )

    ON CONFLICT (clave_dedup) DO NOTHING;

    GET DIAGNOSTICS v_generadas = ROW_COUNT;

    RETURN v_generadas;

END;
$function$;

CREATE OR REPLACE FUNCTION nfc_m28_privado.procesar_alertas_programadas()
 RETURNS TABLE(canceladas integer, generadas integer)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
BEGIN

    -- Primero limpiar avisos pendientes obsoletos.
    canceladas :=
        nfc_m28_privado.cancelar_alertas_pendientes(
            NULL::uuid
        );

    -- Después generar los avisos que correspondan.
    generadas :=
        nfc_m28_privado.generar_alertas_programadas(
            NULL::uuid
        );

    RETURN NEXT;

END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_actualizar_parametro(p_clave text, p_valor text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_tipo text; v_valor text:=btrim(p_valor); v_json jsonb; v_num numeric;
begin
 if not public.es_admin('PARAMETROS_GESTIONAR') then raise exception 'No autorizado.' using errcode='42501'; end if;
 select tipo_dato into v_tipo from public.parametro where clave=p_clave for update;
 if not found then raise exception 'El parámetro no existe.'; end if;
 if v_tipo='ENTERO' and (v_valor is null or v_valor !~ '^-?[0-9]+$') then raise exception 'El valor debe ser un número entero.'; end if;
 if v_tipo='DECIMAL' and (v_valor is null or v_valor !~ '^-?[0-9]+(\.[0-9]+)?$') then raise exception 'El valor debe ser un número decimal.'; end if;
 if v_tipo='BOOLEANO' and (v_valor is null or v_valor not in ('true','false')) then raise exception 'El valor debe ser verdadero o falso.'; end if;
 if v_tipo='TEXTO' and (v_valor is null or char_length(v_valor) not between 1 and 200) then raise exception 'El texto debe tener entre 1 y 200 caracteres.'; end if;
 if v_tipo='JSON' then
   begin v_json:=v_valor::jsonb; if v_json is null then raise exception 'JSON nulo'; end if;
   exception when others then raise exception 'El valor debe ser JSON válido.'; end;
   v_valor:=v_json::text;
 end if;
 if p_clave in ('notif.vencimiento.dias_anticipacion','hogar.max_miembros','hogar.invitacion_vigencia_horas') then
   -- Comparar como numeric evita overflow de int en entradas fuera del rango.
   begin v_num:=v_valor::numeric; exception when others then raise exception 'El valor está fuera del rango permitido.'; end;
   if v_num is null or (p_clave='notif.vencimiento.dias_anticipacion' and v_num not between 0 and 30)
    or (p_clave='hogar.max_miembros' and v_num not between 1 and 20)
    or (p_clave='hogar.invitacion_vigencia_horas' and v_num not between 1 and 720) then raise exception 'El valor está fuera del rango permitido.'; end if;
 end if;
 if p_clave='notif.hora_envio' and (v_valor is null or v_valor !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$') then raise exception 'La hora debe tener formato HH:MM.'; end if;
 if p_clave like '%.canales' then
   if jsonb_typeof(v_json) is distinct from 'array' then raise exception 'Los canales deben ser una lista no vacía de PUSH, EMAIL o IN_APP.'; end if;
   if jsonb_array_length(v_json)=0 or exists(select 1 from jsonb_array_elements(v_json) e where e not in ('"PUSH"'::jsonb,'"EMAIL"'::jsonb,'"IN_APP"'::jsonb))
    or (select count(*) from jsonb_array_elements(v_json))<>(select count(distinct e) from jsonb_array_elements(v_json) e)
    then raise exception 'Los canales deben ser una lista no vacía de PUSH, EMAIL o IN_APP.'; end if;
 end if;
 update public.parametro set valor=v_valor,actualizado_por=auth.uid(),actualizado_en=now() where clave=p_clave;
end;
$function$;

