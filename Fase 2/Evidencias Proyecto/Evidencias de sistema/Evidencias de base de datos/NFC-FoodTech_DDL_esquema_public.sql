CREATE OR REPLACE FUNCTION public.transferir_administracion_hogar(p_hogar_id uuid, p_nuevo_admin uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_yo uuid := auth.uid();
begin
  if not public.es_admin_hogar(p_hogar_id) then
    raise exception 'Solo el administrador puede transferir el hogar.';
  end if;

  if p_nuevo_admin = v_yo then
    raise exception 'Ya eres el administrador de este hogar.';
  end if;

  if not exists (
    select 1
      from public.hogar_miembro
     where hogar_id = p_hogar_id
       and perfil_id = p_nuevo_admin
       and estado = 'ACTIVO'
  ) then
    raise exception 'El usuario no es miembro de este hogar.';
  end if;

  update public.hogar_miembro
     set rol = 'ADMIN'
   where hogar_id = p_hogar_id
     and perfil_id = p_nuevo_admin;

  update public.hogar_miembro
     set rol = 'MIEMBRO'
   where hogar_id = p_hogar_id
     and perfil_id = v_yo;
end;
$function$;

CREATE OR REPLACE FUNCTION public.unirse_hogar(p_codigo text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_hogar public.hogar%rowtype;
  v_perfil uuid := auth.uid();
begin
  if v_perfil is null then
    raise exception 'Debes iniciar sesión para unirte a un hogar.';
  end if;

  select *
    into v_hogar
    from public.hogar
   where upper(codigo_invitacion) = upper(trim(p_codigo))
     and (codigo_invitacion_expira_en is null
          or codigo_invitacion_expira_en > now());

  if not found then
    raise exception 'Código de invitación inválido o expirado.';
  end if;

  if exists (
    select 1
      from public.hogar_miembro
     where hogar_id = v_hogar.id
       and perfil_id = v_perfil
       and estado = 'ACTIVO'
  ) then
    raise exception 'Ya perteneces a este hogar.';
  end if;

  insert into public.hogar_miembro (hogar_id, perfil_id, rol, estado, joined_at)
  values (v_hogar.id, v_perfil, 'MIEMBRO', 'ACTIVO', now())
  on conflict (hogar_id, perfil_id) do update
    set rol = 'MIEMBRO',
        estado = 'ACTIVO',
        joined_at = now();

  return v_hogar.id;
end;
$function$;


