CREATE OR REPLACE FUNCTION public.m15_guardar_hogar(p_hogar_id uuid DEFAULT NULL::uuid, p_nombre text DEFAULT NULL::text, p_adultos smallint DEFAULT NULL::smallint, p_menores smallint DEFAULT NULL::smallint)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_usuario uuid;
    v_hogar uuid;
    v_nombre text;
BEGIN
    v_usuario := auth.uid();
    v_nombre := trim(coalesce(p_nombre, ''));

    IF v_usuario IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM public.perfil p
        WHERE p.id = v_usuario
          AND p.estado_cuenta = 'ACTIVA'
    ) THEN
        RAISE EXCEPTION 'Cuenta no habilitada';
    END IF;

    IF length(v_nombre) < 2 OR length(v_nombre) > 80 THEN
        RAISE EXCEPTION
            'El nombre debe tener entre 2 y 80 caracteres';
    END IF;

    IF p_adultos < 0 OR p_menores < 0 THEN
        RAISE EXCEPTION
            'Las cantidades no pueden ser negativas';
    END IF;

    IF p_hogar_id IS NULL THEN

        IF EXISTS (
            SELECT 1
            FROM public.hogar_miembro hm
            WHERE hm.perfil_id = v_usuario
              AND hm.estado = 'ACTIVO'
        ) THEN
            RAISE EXCEPTION
                'Ya perteneces a un hogar. Debes abandonarlo antes de crear otro';
        END IF;

        INSERT INTO public.hogar (
            nombre,
            adultos,
            menores,
            creado_por
        )
        VALUES (
            v_nombre,
            p_adultos,
            p_menores,
            v_usuario
        )
        RETURNING id INTO v_hogar;

        IF EXISTS (
            SELECT 1
            FROM public.hogar_miembro hm
            WHERE hm.hogar_id = v_hogar
              AND hm.perfil_id = v_usuario
        ) THEN

            UPDATE public.hogar_miembro
            SET rol = 'ADMIN',
                estado = 'ACTIVO',
                joined_at = coalesce(joined_at, now())
            WHERE hogar_id = v_hogar
              AND perfil_id = v_usuario;

        ELSE

            INSERT INTO public.hogar_miembro (
                hogar_id,
                perfil_id,
                rol,
                estado,
                joined_at
            )
            VALUES (
                v_hogar,
                v_usuario,
                'ADMIN',
                'ACTIVO',
                now()
            );

        END IF;

        RETURN v_hogar;
    END IF;

    UPDATE public.hogar h
    SET nombre = v_nombre,
        adultos = p_adultos,
        menores = p_menores,
        updated_at = now()
    WHERE h.id = p_hogar_id
      AND EXISTS (
          SELECT 1
          FROM public.hogar_miembro hm
          WHERE hm.hogar_id = h.id
            AND hm.perfil_id = v_usuario
            AND hm.rol = 'ADMIN'
            AND hm.estado = 'ACTIVO'
      )
    RETURNING h.id INTO v_hogar;

    IF v_hogar IS NULL THEN
        RAISE EXCEPTION
            'No tienes permiso para editar este hogar';
    END IF;

    RETURN v_hogar;
END;
$function$;

CREATE OR REPLACE FUNCTION public.m16_gestionar_miembro(p_hogar_id uuid, p_accion text, p_perfil_id uuid DEFAULT NULL::uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_usuario uuid;
    v_creador uuid;
    v_rol_actual text;
    v_rol_destino text;
    v_cantidad_admin integer;
BEGIN
    v_usuario := auth.uid();

    IF v_usuario IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión';
    END IF;

    -- Serializa las operaciones M16 del mismo hogar.
    SELECT h.creado_por
    INTO v_creador
    FROM public.hogar h
    WHERE h.id = p_hogar_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Hogar no encontrado';
    END IF;

    -- El solicitante debe pertenecer al hogar.
    SELECT hm.rol
    INTO v_rol_actual
    FROM public.hogar_miembro hm
    WHERE hm.hogar_id = p_hogar_id
      AND hm.perfil_id = v_usuario
      AND hm.estado = 'ACTIVO';

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'No perteneces a este hogar';
    END IF;

    -- Contar administradores activos.
    SELECT count(*)
    INTO v_cantidad_admin
    FROM public.hogar_miembro hm
    WHERE hm.hogar_id = p_hogar_id
      AND hm.estado = 'ACTIVO'
      AND hm.rol = 'ADMIN';

    -- ==========================================
    -- ABANDONAR HOGAR
    -- ==========================================
    IF p_accion = 'ABANDONAR' THEN

        IF v_creador = v_usuario THEN
            RAISE EXCEPTION
                'Debes transferir la administración antes de abandonar';
        END IF;

        IF v_rol_actual = 'ADMIN'
           AND v_cantidad_admin <= 1 THEN
            RAISE EXCEPTION
                'El hogar debe conservar un administrador';
        END IF;

        UPDATE public.hogar_miembro
        SET estado = 'REMOVIDO'
        WHERE hogar_id = p_hogar_id
          AND perfil_id = v_usuario
          AND estado = 'ACTIVO';

        RETURN;
    END IF;

    -- Las demás acciones requieren rol ADMIN.
    IF v_rol_actual <> 'ADMIN' THEN
        RAISE EXCEPTION
            'Solo un administrador puede realizar esta acción';
    END IF;

    IF p_perfil_id IS NULL THEN
        RAISE EXCEPTION
            'Debes seleccionar un integrante';
    END IF;

    IF p_perfil_id = v_usuario THEN
        RAISE EXCEPTION
            'Esta acción no se puede realizar sobre tu propia cuenta';
    END IF;

    SELECT hm.rol
    INTO v_rol_destino
    FROM public.hogar_miembro hm
    WHERE hm.hogar_id = p_hogar_id
      AND hm.perfil_id = p_perfil_id
      AND hm.estado = 'ACTIVO';

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'El integrante no está activo en este hogar';
    END IF;

    -- ==========================================
    -- PROMOVER A ADMIN
    -- ==========================================
    IF p_accion = 'PROMOVER' THEN

        UPDATE public.hogar_miembro
        SET rol = 'ADMIN'
        WHERE hogar_id = p_hogar_id
          AND perfil_id = p_perfil_id
          AND estado = 'ACTIVO';

        RETURN;
    END IF;

    -- ==========================================
    -- DEGRADAR A MIEMBRO
    -- ==========================================
    IF p_accion = 'DEGRADAR' THEN

        IF p_perfil_id = v_creador THEN
            RAISE EXCEPTION
                'Primero debes transferir la administración del creador';
        END IF;

        IF v_rol_destino = 'ADMIN'
           AND v_cantidad_admin <= 1 THEN
            RAISE EXCEPTION
                'No puedes quitar al último administrador';
        END IF;

        UPDATE public.hogar_miembro
        SET rol = 'MIEMBRO'
        WHERE hogar_id = p_hogar_id
          AND perfil_id = p_perfil_id
          AND estado = 'ACTIVO';

        RETURN;
    END IF;

    -- ==========================================
    -- REMOVER INTEGRANTE
    -- ==========================================
    IF p_accion = 'REMOVER' THEN

        IF p_perfil_id = v_creador THEN
            RAISE EXCEPTION
                'No puedes remover al creador sin transferir la administración';
        END IF;

        IF v_rol_destino = 'ADMIN'
           AND v_cantidad_admin <= 1 THEN
            RAISE EXCEPTION
                'No puedes remover al último administrador';
        END IF;

        UPDATE public.hogar_miembro
        SET estado = 'REMOVIDO'
        WHERE hogar_id = p_hogar_id
          AND perfil_id = p_perfil_id
          AND estado = 'ACTIVO';

        RETURN;
    END IF;

    -- ==========================================
    -- TRANSFERIR ADMINISTRACIÓN
    -- ==========================================
    IF p_accion = 'TRANSFERIR' THEN

        -- Primero activar como administrador al destino.
        UPDATE public.hogar_miembro
        SET rol = 'ADMIN'
        WHERE hogar_id = p_hogar_id
          AND perfil_id = p_perfil_id
          AND estado = 'ACTIVO';

        -- El administrador actual pasa a MIEMBRO.
        UPDATE public.hogar_miembro
        SET rol = 'MIEMBRO'
        WHERE hogar_id = p_hogar_id
          AND perfil_id = v_usuario
          AND estado = 'ACTIVO';

        -- Si el solicitante era el creador,
        -- transferir también la titularidad técnica.
        IF v_creador = v_usuario THEN
            UPDATE public.hogar
            SET creado_por = p_perfil_id,
                updated_at = now()
            WHERE id = p_hogar_id;
        END IF;

        RETURN;
    END IF;

    RAISE EXCEPTION 'Acción no válida';
END;
$function$;

CREATE OR REPLACE FUNCTION public.m16_listar_miembros(p_hogar_id uuid)
 RETURNS TABLE(perfil_id uuid, nombre text, apellido text, rol text, estado text, joined_at timestamp with time zone, es_creador boolean)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión';
