    -- para coordinar operaciones concurrentes.
    PERFORM 1
    FROM public.hogar h
    WHERE h.id = p_hogar_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Hogar no encontrado';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM public.hogar_miembro hm
        WHERE hm.hogar_id = p_hogar_id
          AND hm.perfil_id = v_usuario
          AND hm.rol = 'ADMIN'
          AND hm.estado = 'ACTIVO'
    ) THEN
        RAISE EXCEPTION
            'Solo un administrador puede generar invitaciones';
    END IF;

    -- Código aleatorio de 16 caracteres hexadecimales.
    -- Comprobar que no coincida con otro código vigente.

    FOR v_intento IN 1..10 LOOP
        v_codigo := upper(
            substring(
                replace(
                    pg_catalog.gen_random_uuid()::text,
                    '-',
                    ''
                )
                FROM 1 FOR 16
            )
        );

        EXIT WHEN NOT EXISTS (
            SELECT 1
            FROM public.hogar h
            WHERE h.codigo_invitacion = v_codigo
              AND h.codigo_invitacion_expira_en > now()
        );
    END LOOP;

    IF EXISTS (
        SELECT 1
        FROM public.hogar h
        WHERE h.codigo_invitacion = v_codigo
          AND h.codigo_invitacion_expira_en > now()
    ) THEN
        RAISE EXCEPTION
            'No fue posible generar un código único';
    END IF;

    v_expira := now() + interval '24 hours';

    UPDATE public.hogar
    SET codigo_invitacion = v_codigo,
        codigo_invitacion_expira_en = v_expira,
        updated_at = now()
    WHERE id = p_hogar_id;

    RETURN jsonb_build_object(
        'exito', true,
        'codigo', v_codigo,
        'expira_en', v_expira
    );
END;
$function$;

CREATE OR REPLACE FUNCTION public.m17_unirse_hogar(p_codigo text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_usuario uuid := auth.uid();
    v_codigo text;
    v_hogar_id uuid;
    v_nombre text;
    v_estado text;
BEGIN
    IF v_usuario IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM public.perfil p
        WHERE p.id = v_usuario
          AND p.estado_cuenta = 'ACTIVA'
    ) THEN
        RAISE EXCEPTION 'Cuenta no habilitada';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.hogar_miembro hm
        WHERE hm.perfil_id = v_usuario
          AND hm.estado = 'ACTIVO'
    ) THEN
        RAISE EXCEPTION
            'Ya perteneces a un hogar. Debes abandonarlo antes de unirte a otro';
    END IF;

    v_codigo := upper(trim(coalesce(p_codigo, '')));

    IF v_codigo !~ '^[A-F0-9]{16}$' THEN
        RAISE EXCEPTION 'Código de invitación inválido';
    END IF;

    SELECT h.id, h.nombre
    INTO v_hogar_id, v_nombre
    FROM public.hogar h
    WHERE h.codigo_invitacion = v_codigo
      AND h.codigo_invitacion_expira_en > now()
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Código incorrecto o vencido';
    END IF;

    SELECT hm.estado
    INTO v_estado
    FROM public.hogar_miembro hm
    WHERE hm.hogar_id = v_hogar_id
      AND hm.perfil_id = v_usuario;

    IF FOUND THEN
        IF v_estado = 'ACTIVO' THEN
            RAISE EXCEPTION
                'Ya perteneces a este hogar';
        END IF;

        IF v_estado = 'REMOVIDO' THEN
            RAISE EXCEPTION
                'Debes solicitar una nueva autorización para volver';
        END IF;

        IF v_estado = 'INVITADO' THEN
            UPDATE public.hogar_miembro
            SET estado = 'ACTIVO',
                joined_at = now()
            WHERE hogar_id = v_hogar_id
              AND perfil_id = v_usuario;
        ELSE
            RAISE EXCEPTION
                'Estado de membresía no permitido';
        END IF;

    ELSE
        INSERT INTO public.hogar_miembro (
            hogar_id,
            perfil_id,
            rol,
            estado,
            joined_at
        )
        VALUES (
            v_hogar_id,
            v_usuario,
            'MIEMBRO',
            'ACTIVO',
            now()
        );
    END IF;

    RETURN jsonb_build_object(
        'exito', true,
        'hogar_id', v_hogar_id,
        'nombre', v_nombre,
        'rol', 'MIEMBRO'
    );
END;
$function$;

CREATE OR REPLACE FUNCTION public.m19_autocalcular_vencimiento()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_dias integer;
    v_dias_alimento integer;
    v_dias_categoria integer;
    v_dias_refrigerador integer;
    v_dias_congelador integer;
    v_temp text;
    v_perecible boolean;
BEGIN
    -- Si existe una fecha manual o personalizada,
    -- respetarla completamente.
    IF NEW.fecha_vencimiento IS NOT NULL THEN
        RETURN NEW;
    END IF;

    -- Buscar las referencias del alimento y su categoría.
    SELECT
        a.vida_util_dias_ref,
        c.vida_util_dias_ref,
        c.vida_util_refrigerado_dias,
        c.vida_util_congelado_dias,
        c.temp_conservacion,
        a.es_perecible
    INTO
        v_dias_alimento,
        v_dias_categoria,
        v_dias_refrigerador,
        v_dias_congelador,
        v_temp,
        v_perecible
    FROM public.alimento a
    JOIN public.categoria c
        ON c.id = a.categoria_id
    WHERE a.id = NEW.alimento_id;

    -- Si el alimento no es perecible, no estimar.
    IF v_perecible IS NOT TRUE THEN
        NEW.vencimiento_estimado := false;
        RETURN NEW;
    END IF;

    -- Elegir una duración referencial según ubicación.
    CASE NEW.ubicacion
        WHEN 'DESPENSA' THEN
            IF v_temp IS NULL OR v_temp = 'AMBIENTE' THEN
                v_dias := COALESCE(
                    v_dias_alimento,
                    v_dias_categoria
                );
            END IF;

        WHEN 'REFRIGERADOR' THEN
            IF v_temp IS NULL OR v_temp = 'REFRIGERADO' THEN
                v_dias := COALESCE(
                    v_dias_alimento,
                    v_dias_refrigerador,
                    v_dias_categoria
                );
            ELSE
                v_dias := v_dias_refrigerador;
            END IF;

        WHEN 'CONGELADOR' THEN
            IF v_temp = 'CONGELADO' THEN
                v_dias := COALESCE(
                    v_dias_alimento,
                    v_dias_congelador,
                    v_dias_categoria
                );
            ELSE
                v_dias := v_dias_congelador;
            END IF;
    END CASE;

    IF v_dias IS NOT NULL AND v_dias > 0 THEN
        NEW.fecha_vencimiento :=
            NEW.fecha_ingreso + v_dias;

        NEW.vencimiento_estimado := true;
    ELSE
        -- No inventar fechas cuando faltan referencias.
        NEW.fecha_vencimiento := NULL;
        NEW.vencimiento_estimado := false;
    END IF;

    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.m19_registrar_multiples(p_hogar_id uuid, p_items jsonb)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_usuario uuid := auth.uid();
    v_item jsonb;

    v_alimento_id bigint;
    v_cantidad numeric;
    v_ubicacion text;
    v_fecha date;
    v_estimado boolean;
    v_precio integer;

    v_total integer := 0;
BEGIN
    -- 1. Validar autenticación.
    IF v_usuario IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión';
    END IF;

    -- 2. Validar hogar y miembro activo.
    IF p_hogar_id IS NULL OR NOT EXISTS (
        SELECT 1
        FROM public.hogar_miembro hm
        JOIN public.perfil p
            ON p.id = hm.perfil_id
        WHERE hm.hogar_id = p_hogar_id
          AND hm.perfil_id = v_usuario
          AND hm.estado = 'ACTIVO'
          AND p.estado_cuenta = 'ACTIVA'
    ) THEN
        RAISE EXCEPTION
            'No tienes permiso para registrar en este hogar';
    END IF;

    -- 3. Verificar formato del conjunto.
    IF p_items IS NULL
       OR jsonb_typeof(p_items) <> 'array'
    THEN
        RAISE EXCEPTION
            'Los alimentos deben enviarse como un arreglo';
    END IF;

    IF jsonb_array_length(p_items) < 1
       OR jsonb_array_length(p_items) > 50
    THEN
        RAISE EXCEPTION
            'Debes registrar entre 1 y 50 alimentos';
    END IF;

    -- 4. Recorrer cada alimento.
    FOR v_item IN
        SELECT value
        FROM jsonb_array_elements(p_items)
    LOOP
        IF jsonb_typeof(v_item) <> 'object' THEN
            RAISE EXCEPTION
                'Cada alimento debe ser un objeto válido';
        END IF;

        v_alimento_id :=
            NULLIF(v_item->>'alimento_id', '')::bigint;

        v_cantidad :=
            NULLIF(v_item->>'cantidad', '')::numeric;

        v_ubicacion := v_item->>'ubicacion';

        v_fecha :=
            NULLIF(
                v_item->>'fecha_vencimiento',
                ''
            )::date;

        v_estimado := COALESCE(
            (v_item->>'vencimiento_estimado')::boolean,
            false
        );

        v_precio :=
            NULLIF(v_item->>'precio_clp', '')::integer;

        -- 5. Validar cantidad.
        IF v_cantidad IS NULL
           OR v_cantidad <= 0
           OR v_cantidad > 9999999.999
           OR v_cantidad <> round(v_cantidad, 3)
        THEN
            RAISE EXCEPTION
                'Cantidad inválida para alimento %',
                v_alimento_id;
        END IF;

        -- 6. Validar ubicación.
        IF v_ubicacion IS NULL
           OR v_ubicacion NOT IN (
               'DESPENSA',
               'REFRIGERADOR',
               'CONGELADOR'
           )
        THEN
            RAISE EXCEPTION
                'Ubicación inválida para alimento %',
                v_alimento_id;
        END IF;

        -- 7. Validar precio opcional.
        IF v_precio IS NOT NULL AND v_precio < 0 THEN
            RAISE EXCEPTION
                'El precio no puede ser negativo';
        END IF;

        -- 8. Validar que el alimento sea accesible.
        IF v_alimento_id IS NULL OR NOT EXISTS (
            SELECT 1
            FROM public.alimento a
            WHERE a.id = v_alimento_id
              AND a.activo = true
              AND (
                  (
                      a.estado = 'APROBADO'
                      AND a.hogar_id IS NULL
                  )
                  OR (
                      a.hogar_id = p_hogar_id
                      AND a.estado IN (
                          'LOCAL',
                          'PROPUESTO',
                          'RECHAZADO'
                      )
                  )
              )
        ) THEN
            RAISE EXCEPTION
                'Alimento no disponible: %',
                v_alimento_id;
        END IF;

        -- 9. Crear una entrada independiente.
        INSERT INTO public.despensa_item (
            id,
            hogar_id,
            alimento_id,
            cantidad_inicial,
            cantidad_restante,
            fecha_ingreso,
            fecha_vencimiento,
            vencimiento_estimado,
            ubicacion,
            estado,
            precio_clp
        )
        VALUES (
            gen_random_uuid(),
            p_hogar_id,
            v_alimento_id,
            v_cantidad,
            v_cantidad,
            (now() AT TIME ZONE 'America/Santiago')::date,
            v_fecha,
            v_estimado,
            v_ubicacion,
            'DISPONIBLE',
            v_precio
        );

        v_total := v_total + 1;
    END LOOP;

    RETURN v_total;
END;
$function$;

CREATE OR REPLACE FUNCTION public.m27_confirmar_compra_item(p_lista_item_id uuid, p_ubicacion text, p_fecha_vencimiento date DEFAULT NULL::date, p_precio_clp integer DEFAULT NULL::integer)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_item public.lista_compra_item%ROWTYPE;

    v_hogar_id uuid;
    v_estado_lista text;

    v_unidad_base text;
    v_alimento_hogar_id uuid;
    v_estado_alimento text;

    v_cantidad_base numeric;
    v_despensa_item_id uuid;
BEGIN

    -- 1. Usuario autenticado.
    IF (SELECT auth.uid()) IS NULL THEN
        RAISE EXCEPTION
            'Debes iniciar sesión.';
    END IF;

    -- 2. Bloquear el ítem.
    -- Impide duplicarlo ante dos confirmaciones simultáneas.
    SELECT *
    INTO v_item
    FROM public.lista_compra_item
    WHERE id = p_lista_item_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'El producto no existe en la lista.';
    END IF;

    -- 3. Obtener el hogar y estado de la lista.
    SELECT hogar_id, estado
    INTO v_hogar_id, v_estado_lista
    FROM public.lista_compra
    WHERE id = v_item.lista_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'La lista de compras no existe.';
    END IF;

    IF NOT public.es_miembro_hogar(v_hogar_id) THEN
        RAISE EXCEPTION
            'No perteneces a este hogar.';
    END IF;

    -- 4. Si ya existe un ingreso vinculado,
    -- no crear otro.
    IF v_item.despensa_item_id IS NOT NULL THEN

        SELECT id
        INTO v_despensa_item_id
        FROM public.despensa_item
        WHERE id = v_item.despensa_item_id
          AND hogar_id = v_hogar_id
          AND alimento_id = v_item.alimento_id;

        IF NOT FOUND THEN
            RAISE EXCEPTION
                'El ingreso vinculado no es válido.';
        END IF;

        RETURN v_despensa_item_id;
    END IF;

    -- 5. Solo convertir compras de listas abiertas.
    IF v_estado_lista <> 'ABIERTA' THEN
        RAISE EXCEPTION
            'La lista de compras no está abierta.';
    END IF;

    -- Se aceptan los COMPRADO antiguos sin vinculación,
    -- además de los PENDIENTE actuales.
    IF v_item.estado NOT IN ('PENDIENTE', 'COMPRADO') THEN
        RAISE EXCEPTION
            'Este producto no se puede ingresar.';
    END IF;

    -- 6. Validar ubicación.
    IF p_ubicacion IS NULL OR
       p_ubicacion NOT IN (
           'DESPENSA',
           'REFRIGERADOR',
           'CONGELADOR'
       )
    THEN
        RAISE EXCEPTION
            'Ubicación no válida.';
    END IF;

    IF p_precio_clp IS NOT NULL
       AND p_precio_clp < 0
    THEN
        RAISE EXCEPTION
            'El precio no puede ser negativo.';
    END IF;

    -- 7. Validar alimento y ámbito del hogar.
    SELECT unidad_base, hogar_id, estado
    INTO
        v_unidad_base,
        v_alimento_hogar_id,
        v_estado_alimento
    FROM public.alimento
    WHERE id = v_item.alimento_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'El alimento no existe.';
    END IF;

    IF NOT (
        (
            v_alimento_hogar_id IS NULL
            AND v_estado_alimento = 'APROBADO'
        )
        OR v_alimento_hogar_id = v_hogar_id
    ) THEN
        RAISE EXCEPTION
            'El alimento no está disponible para este hogar.';
    END IF;

    -- 8. Validar compatibilidad de unidades.
    IF (
        v_unidad_base = 'g'
        AND v_item.unidad NOT IN ('g', 'kg')
    ) OR (
        v_unidad_base = 'ml'
        AND v_item.unidad NOT IN ('ml', 'l')
    ) OR (
        v_unidad_base = 'un'
        AND v_item.unidad <> 'un'
    ) THEN
        RAISE EXCEPTION
            'La unidad de compra no coincide con el alimento.';
    END IF;

    -- 9. Convertir a unidad base.
    v_cantidad_base :=
        CASE
            WHEN v_item.unidad IN ('kg', 'l')
                THEN v_item.cantidad * 1000
            ELSE v_item.cantidad
        END;

    IF v_cantidad_base <= 0
       OR v_cantidad_base > 9999999.999
    THEN
        RAISE EXCEPTION
            'La cantidad está fuera del rango permitido.';
    END IF;

    -- Máximo tres decimales en unidad base.
    IF v_cantidad_base <>
       round(v_cantidad_base, 3)
    THEN
        RAISE EXCEPTION
            'La cantidad supera la precisión permitida.';
    END IF;

    -- 10. Registrar nuevo ingreso.
    -- Los triggers de despensa_item realizan
    -- la estimación de fecha y el movimiento INGRESO.
    INSERT INTO public.despensa_item (
        hogar_id,
        alimento_id,
        cantidad_inicial,
        cantidad_restante,
        fecha_vencimiento,
        vencimiento_estimado,
        ubicacion,
        estado,
        precio_clp
    )
    VALUES (
        v_hogar_id,
        v_item.alimento_id,
        v_cantidad_base,
        v_cantidad_base,
        p_fecha_vencimiento,
        false,
        p_ubicacion,
        'DISPONIBLE',
        p_precio_clp
    )
    RETURNING id INTO v_despensa_item_id;

    -- 11. Vincular compra con el ingreso.
    UPDATE public.lista_compra_item
    SET
        estado = 'COMPRADO',
        despensa_item_id = v_despensa_item_id
    WHERE id = v_item.id;

    RETURN v_despensa_item_id;

END;
$function$;

CREATE OR REPLACE FUNCTION public.m28_generar_alertas_internas()
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_usuario uuid;
    v_insertadas integer := 0;
BEGIN

    -- 1. Comprobar sesión.
    v_usuario := (SELECT auth.uid());

    IF v_usuario IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión.';
    END IF;

    -- 2. Respetar la protección de cuentas M08.
    IF NOT COALESCE(
        nfc_seguridad.cuenta_activa(),
        false
    ) THEN
        RAISE EXCEPTION 'La cuenta no está activa.';
    END IF;

    -- 3. Generar notificaciones según las preferencias.
    INSERT INTO public.notificacion (
        perfil_id,
        plantilla_id,
        despensa_item_id,
        datos,
        estado,
        programada_para,
        clave_dedup
    )
    SELECT
        per.id,

        -- Plantilla del mensaje:
        -- cambia según si la fecha es estimada
        -- o fue ingresada manualmente.
        plantilla_mensaje.id,

        d.id,

        jsonb_build_object(
            'alimento', a.nombre,
            'dias', GREATEST(
                d.fecha_vencimiento - fechas.hoy,
                0
            ),
            'fecha', d.fecha_vencimiento,
            'hogar', h.nombre,
            'cantidad', d.cantidad_restante,
            'unidad', a.unidad_base,
            'vencimiento_estimado',
                d.vencimiento_estimado,
            'origen_fecha',
                CASE
                    WHEN d.vencimiento_estimado
                        THEN 'ESTIMADA'
                    ELSE 'MANUAL'
                END
        ),

        'PENDIENTE',

        now(),

        concat(
            'm28:',
            per.id::text, ':',
            plantilla_mensaje.id::text, ':',
            d.id::text, ':',
            d.fecha_vencimiento::text
        )

    FROM public.perfil per

    JOIN public.hogar_miembro hm
        ON hm.perfil_id = per.id
       AND hm.estado = 'ACTIVO'

    JOIN public.hogar h
        ON h.id = hm.hogar_id

    JOIN public.despensa_item d
        ON d.hogar_id = hm.hogar_id
       AND d.estado = 'DISPONIBLE'
       AND d.cantidad_restante > 0
       AND d.fecha_vencimiento IS NOT NULL

    JOIN public.alimento a
        ON a.id = d.alimento_id

    -- Preferencias del usuario.
    JOIN public.preferencia_notificacion pref
        ON pref.perfil_id = per.id
       AND pref.habilitada = true

    -- La preferencia sigue siendo una de las
    -- dos categorías originales.
    JOIN public.plantilla_notificacion
        AS plantilla_preferencia
        ON plantilla_preferencia.id = pref.plantilla_id
       AND plantilla_preferencia.codigo IN (
           'VENCIMIENTO_PROXIMO',
           'PRODUCTO_VENCIDO'
       )

    -- Seleccionar el texto correcto para
    -- cada combinación de alerta y origen.
    JOIN public.plantilla_notificacion
        AS plantilla_mensaje
        ON plantilla_mensaje.codigo =
            CASE
                WHEN
                    plantilla_preferencia.codigo =
                    'VENCIMIENTO_PROXIMO'
                    AND d.vencimiento_estimado = true
                    THEN 'VENCIMIENTO_PROXIMO'

                WHEN
                    plantilla_preferencia.codigo =
                    'VENCIMIENTO_PROXIMO'
                    AND d.vencimiento_estimado = false
                    THEN 'FECHA_INDICADA_PROXIMA'

                WHEN
                    plantilla_preferencia.codigo =
                    'PRODUCTO_VENCIDO'
                    AND d.vencimiento_estimado = true
                    THEN 'PRODUCTO_VENCIDO'

                ELSE 'FECHA_INDICADA_SUPERADA'
            END

    CROSS JOIN LATERAL (
        SELECT (
            now() AT TIME ZONE per.zona_horaria
        )::date AS hoy
    ) AS fechas

    WHERE per.id = v_usuario

      AND (
          -- Próximas: dentro de la anticipación.
          (
              plantilla_preferencia.codigo =
                  'VENCIMIENTO_PROXIMO'

              AND d.fecha_vencimiento >= fechas.hoy

              AND d.fecha_vencimiento <=
                  fechas.hoy + LEAST(
                      COALESCE(
                          pref.dias_anticipacion,
                          3
                      ),
                      14
                  )
          )

          OR

          -- Fecha ya superada.
          (
              plantilla_preferencia.codigo =
                  'PRODUCTO_VENCIDO'

              AND d.fecha_vencimiento < fechas.hoy
          )
      )

    ON CONFLICT (clave_dedup) DO NOTHING;

    GET DIAGNOSTICS v_insertadas = ROW_COUNT;

    RETURN v_insertadas;

END;
$function$;

CREATE OR REPLACE FUNCTION public.m28_sincronizar_alertas()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_usuario uuid;
    v_canceladas integer;
    v_generadas integer;
BEGIN

    v_usuario := (SELECT auth.uid());

    IF v_usuario IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión';
    END IF;

    IF NOT COALESCE(
        nfc_seguridad.cuenta_activa(),
        false
    ) THEN
        RAISE EXCEPTION 'La cuenta no está activa';
    END IF;

    -- Limpiar exclusivamente los avisos propios.
    v_canceladas :=
        nfc_m28_privado.cancelar_alertas_pendientes(
            v_usuario
