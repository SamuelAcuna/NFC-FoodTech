CREATE OR REPLACE FUNCTION public.registrar_fecha_precio_compra()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_precio integer;
BEGIN
    -- Se ejecuta cuando una compra queda
    -- vinculada por primera vez a un ingreso.
    IF NEW.despensa_item_id IS NOT NULL
       AND OLD.despensa_item_id IS DISTINCT FROM
           NEW.despensa_item_id
    THEN
        SELECT di.precio_clp
        INTO v_precio
        FROM public.despensa_item di
        WHERE di.id = NEW.despensa_item_id;

        NEW.fecha_compra := now();
        NEW.precio_compra_clp := v_precio;

    -- Una vez confirmado el ingreso, las ediciones
    -- posteriores no sobrescriben el valor histórico.
    ELSIF OLD.despensa_item_id IS NOT NULL THEN
        NEW.fecha_compra := OLD.fecha_compra;
        NEW.precio_compra_clp :=
            OLD.precio_compra_clp;
    END IF;

    RETURN NEW;
END;
$function$;

