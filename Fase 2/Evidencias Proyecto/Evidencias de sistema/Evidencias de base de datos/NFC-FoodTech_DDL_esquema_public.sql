  if not public.es_admin_hogar(p_hogar_id) then
    raise exception 'Solo el administrador puede generar códigos de invitación.';
  end if;

  select upper(regexp_replace(coalesce(nombre, ''), '[^A-Za-z0-9]', '', 'g'))
    into v_nombre
    from public.hogar
   where id = p_hogar_id;

  v_codigo := 'INV_'
    || left(coalesce(nullif(v_nombre, ''), 'HOGAR'), 14)
    || '_'
    || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6));

  update public.hogar
     set codigo_invitacion = v_codigo,
         codigo_invitacion_expira_en = now() + interval '7 days',
         updated_at = now()
   where id = p_hogar_id;

  return v_codigo;
end;
$function$;

