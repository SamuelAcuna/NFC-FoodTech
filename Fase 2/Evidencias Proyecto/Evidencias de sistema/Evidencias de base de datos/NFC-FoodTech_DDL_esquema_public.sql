CREATE OR REPLACE FUNCTION public.m08_iniciar_confirmacion_prueba(p_usuario uuid, p_sesion uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_solicitud uuid;
    v_vence timestamptz;
    v_revision jsonb;
BEGIN

    -- 1. Solo puede llamarla el backend.
    IF auth.role() IS DISTINCT FROM 'service_role' THEN
        RAISE EXCEPTION 'Acceso no autorizado';
    END IF;

    -- 2. Exclusivamente nuestra cuenta de prueba.
    IF p_usuario IS DISTINCT FROM
        '9935ceb5-7be9-4d03-becf-3504c8e617c5'::uuid
    THEN
        RAISE EXCEPTION 'Cuenta no autorizada';
    END IF;

    -- 3. Verificar sesión y propietario.
    IF NOT EXISTS (
        SELECT 1
        FROM auth.sessions s
        WHERE s.id = p_sesion
          AND s.user_id = p_usuario
    ) THEN
        RAISE EXCEPTION 'Sesión no válida';
    END IF;

    -- 4. Exigir cuenta ACTIVA.
    -- Bloquear el perfil durante esta operación
    -- para evitar solicitudes simultáneas.
    PERFORM 1
    FROM public.perfil p
    WHERE p.id = p_usuario
      AND p.estado_cuenta = 'ACTIVA'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Cuenta no activa';
    END IF;

    -- 5. Reutilizar nuestra revisión preliminar.
    v_revision :=
        public.m08_preflight_eliminacion_prueba(
            p_usuario
        );

    IF COALESCE(
        (v_revision ->> 'apto')::boolean,
        false
    ) IS NOT TRUE THEN
        RAISE EXCEPTION
            'La cuenta tiene requisitos pendientes';
    END IF;

    -- 6. Cancelar solicitudes pendientes anteriores.
    UPDATE public.m08_confirmacion_eliminacion
    SET estado = 'CANCELADA'
    WHERE usuario_id = p_usuario
      AND estado = 'PENDIENTE';

    -- 7. Crear solicitud nueva.
    INSERT INTO public.m08_confirmacion_eliminacion (
        usuario_id,
        sesion_id
    )
    VALUES (
        p_usuario,
        p_sesion
    )
    RETURNING id, vence_en
    INTO v_solicitud, v_vence;

    -- 8. Responder sin autorizar la eliminación.
    RETURN jsonb_build_object(
        'exito', true,
        'solicitud_id', v_solicitud,
        'estado', 'PENDIENTE',
        'vence_en', v_vence,
        'eliminacion_autorizada', false
    );

END;
$function$;

CREATE OR REPLACE FUNCTION public.m08_preflight_eliminacion_prueba(p_usuario uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE
 SET search_path TO ''
AS $function$
DECLARE
    v_estado text;
    v_hogares bigint;
    v_membresias bigint;
    v_soporte bigint;
    v_archivos bigint;
    v_auditoria bigint;
    v_historial bigint;
    v_apto boolean;
BEGIN

    -- Acceso exclusivo del backend administrativo.
    IF auth.role() IS DISTINCT FROM 'service_role' THEN
        RAISE EXCEPTION 'Acceso no autorizado';
    END IF;

    -- Estado de cuenta.
    SELECT p.estado_cuenta
    INTO v_estado
    FROM public.perfil p
    WHERE p.id = p_usuario;

    -- Hogares creados.
    SELECT COUNT(*)
    INTO v_hogares
    FROM public.hogar h
    WHERE h.creado_por = p_usuario;

    -- Membresías.
    SELECT COUNT(*)
    INTO v_membresias
    FROM public.hogar_miembro hm
    WHERE hm.perfil_id = p_usuario;

    -- Solicitudes de soporte.
    SELECT COUNT(*)
    INTO v_soporte
    FROM public.solicitud_soporte s
    WHERE s.solicitado_por = p_usuario
       OR s.asignado_a = p_usuario
       OR s.respondido_por = p_usuario;

    -- Archivos del usuario.
    SELECT COUNT(*)
    INTO v_archivos
    FROM storage.objects o
    WHERE o.owner_id = p_usuario::text
       OR (
           o.bucket_id = 'fotos_perfil'
           AND o.name LIKE p_usuario::text || '/%'
       );

    -- Auditoría.
    SELECT COUNT(*)
    INTO v_auditoria
    FROM public.auditoria a
    WHERE a.perfil_id = p_usuario
       OR a.entidad_id = p_usuario::text
       OR COALESCE(a.antes::text, '') LIKE
          '%' || p_usuario::text || '%'
       OR COALESCE(a.despues::text, '') LIKE
          '%' || p_usuario::text || '%';

    -- Historial vigente.
    -- Se retira exclusivamente el conteo
    -- de la tabla public.compra.
    SELECT
        (
            SELECT COUNT(*)
            FROM public.movimiento
            WHERE registrado_por = p_usuario
        )
        +
        (
            SELECT COUNT(*)
            FROM public.lista_compra
            WHERE creada_por = p_usuario
        )
        +
        (
            SELECT COUNT(*)
            FROM public.lista_compra_item
            WHERE agregado_por = p_usuario
        )
        +
        (
            SELECT COUNT(*)
            FROM public.alimento
            WHERE creado_por = p_usuario
        )
    INTO v_historial;

    -- Mantener todas las condiciones.
    v_apto :=
        COALESCE(v_estado = 'ACTIVA', false)
        AND v_hogares = 0
        AND v_membresias = 0
        AND v_soporte = 0
        AND v_archivos = 0
        AND v_auditoria = 0
        AND v_historial = 0;

    -- Mantener el contrato de respuesta.
    RETURN jsonb_build_object(
        'apto', v_apto,
        'estado_cuenta', v_estado,
        'hogares', v_hogares,
        'membresias', v_membresias,
        'soporte', v_soporte,
        'archivos', v_archivos,
        'auditoria', v_auditoria,
        'historial', v_historial
    );

END;
$function$;

