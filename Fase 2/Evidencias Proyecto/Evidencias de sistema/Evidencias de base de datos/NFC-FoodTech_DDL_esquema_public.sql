CREATE OR REPLACE FUNCTION public.registrar_movimiento_despensa(p_despensa_item_id uuid, p_tipo text, p_cantidad numeric, p_tipo_desperdicio_id bigint DEFAULT NULL::bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_yo uuid := auth.uid();
  v_hogar uuid;
  v_restante numeric;
  v_tipo text := upper(trim(p_tipo));
  v_agota boolean;
begin
  if v_yo is null then
    raise exception 'Debes iniciar sesión.';
  end if;

  if v_tipo not in ('CONSUMO', 'DESCARTE') then
    raise exception 'Tipo de movimiento no válido.';
  end if;

  select hogar_id, cantidad_restante
    into v_hogar, v_restante
    from public.despensa_item
   where id = p_despensa_item_id
   for update;

  if not found then
    raise exception 'El ítem no existe.';
  end if;

  if not public.es_miembro_hogar(v_hogar) then
    raise exception 'No tienes acceso a este ítem.';
  end if;

  if p_cantidad is null or p_cantidad <= 0 then
    raise exception 'La cantidad debe ser mayor que cero.';
  end if;

  if p_cantidad > v_restante then
    raise exception 'La cantidad supera lo disponible en el ítem.';
  end if;

  if v_tipo = 'DESCARTE' then
    if p_tipo_desperdicio_id is null then
      raise exception 'Un descarte necesita un motivo.';
    end if;

    if not exists (
      select 1
      from public.tipo_desperdicio td
      where td.id = p_tipo_desperdicio_id
        and td.activo = true
    ) then
      raise exception 'El motivo de descarte no existe.';
    end if;
  else
    if p_tipo_desperdicio_id is not null then
      raise exception 'Un consumo no lleva motivo de descarte.';
    end if;
  end if;

  insert into public.movimiento
    (despensa_item_id, tipo, cantidad, tipo_desperdicio_id, registrado_por, fecha)
  values
    (p_despensa_item_id, v_tipo, p_cantidad, p_tipo_desperdicio_id, v_yo, now());

  v_agota := (v_restante - p_cantidad) <= 0;

  update public.despensa_item
     set cantidad_restante = round(cantidad_restante - p_cantidad, 3),
         estado = case
           when v_agota and v_tipo = 'DESCARTE' then 'DESECHADO'
           when v_agota then 'AGOTADO'
           else estado
         end
   where id = p_despensa_item_id;
end;
$function$;

CREATE OR REPLACE FUNCTION public.revocar_miembro_hogar(p_hogar_id uuid, p_perfil_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_yo uuid := auth.uid();
begin
  if not public.es_admin_hogar(p_hogar_id) then
    raise exception 'Solo el administrador puede revocar accesos.';
  end if;

  if p_perfil_id = v_yo then
    raise exception 'Para salir del hogar usa la opción Abandonar hogar.';
  end if;

  if not exists (
    select 1
      from public.hogar_miembro
     where hogar_id = p_hogar_id
       and perfil_id = p_perfil_id
       and estado = 'ACTIVO'
  ) then
    raise exception 'El usuario no es miembro de este hogar.';
  end if;

  update public.hogar_miembro
     set estado = 'REMOVIDO'
   where hogar_id = p_hogar_id
     and perfil_id = p_perfil_id;
end;
$function$;

CREATE OR REPLACE FUNCTION public.rls_auto_enable()
 RETURNS event_trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog'
AS $function$
DECLARE
  cmd record;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        EXECUTE format('alter table if exists %s enable row level security', cmd.object_identity);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION public.salir_hogar(p_hogar_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_yo uuid := auth.uid();
  v_rol text;
  v_admins integer;
begin
  if not public.es_miembro_hogar(p_hogar_id) then
    raise exception 'No perteneces a este hogar.';
  end if;

  select rol into v_rol
    from public.hogar_miembro
   where hogar_id = p_hogar_id
     and perfil_id = v_yo
     and estado = 'ACTIVO';

  if v_rol = 'ADMIN' then
    select count(*) into v_admins
      from public.hogar_miembro
     where hogar_id = p_hogar_id
       and estado = 'ACTIVO'
       and rol = 'ADMIN';

    if v_admins <= 1 then
      raise exception 'Eres el único administrador. Transfiere la administración antes de abandonar el hogar.';
    end if;
  end if;

  update public.hogar_miembro
     set estado = 'REMOVIDO'
   where hogar_id = p_hogar_id
     and perfil_id = v_yo;
end;
$function$;

