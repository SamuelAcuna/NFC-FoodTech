CREATE OR REPLACE FUNCTION public.admin_reporte_uso(p_desde date, p_hasta date, p_agrupacion text DEFAULT 'MES'::text)
 RETURNS TABLE(periodo date, altas integer, usuarios_activos integer, retencion_pct numeric, productos_registrados integer, alertas_emitidas integer)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
