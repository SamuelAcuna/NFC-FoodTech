CREATE OR REPLACE FUNCTION public.admin_reporte_desperdicio(p_desde date, p_hasta date, p_agrupacion text DEFAULT 'MES'::text)
 RETURNS TABLE(periodo date, categoria text, descartes integer, hogares integer)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_unit text;
begin
 if not public.es_admin('REPORTES_VER') then raise exception 'No autorizado.' using errcode='42501'; end if;
 if p_desde is null or p_hasta is null or p_desde>p_hasta then raise exception 'El rango de fechas no es válido.'; end if;
