CREATE OR REPLACE FUNCTION public.m17_generar_invitacion(p_hogar_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_usuario uuid := auth.uid();
    v_codigo text;
    v_expira timestamptz;
    v_intento integer;
BEGIN
    IF v_usuario IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM public.perfil p
        WHERE p.id = v_usuario
          AND p.estado_cuenta = 'ACTIVA'
    ) THEN
