 v_unit:=case when p_agrupacion='MES' then 'month' else 'week' end;
 return query select date_trunc(v_unit,m.fecha at time zone 'America/Santiago')::date,raiz.nombre,count(*)::int,count(distinct d.hogar_id)::int
